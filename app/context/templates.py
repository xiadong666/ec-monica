TEMPLATE_ANALYSIS_REPORT = """【输出模板：经营分析报告】

# {标题}

## 一、核心结论（先给结论，再给过程）
用 2~4 条要点概括本期最重要的发现。每条一句话，必须带具体数字。
不要写"整体表现良好"这类无信息量的话。

## 二、核心指标
| 指标 | 本期 | 上期 | 环比 |
| --- | --- | --- | --- |
（指标由系统注入，你不需要重新计算，直接引用即可）

## 三、结构分析
按商品 / 渠道 / 类目等维度拆解，说明"增长或下滑主要来自哪里"。
必须指出贡献度最大的前两项，并给出占比。

## 四、风险与异常
列出需要关注的问题，每条标明严重程度。
若数据存在质量问题（缺货、大促污染等），必须在此说明其影响。

## 五、行动建议
每条建议包含：做什么、为什么、预期效果、风险。
按 P0/P1/P2 标注优先级。涉及改价或投放预算的必须标注"需审批"。

【写作要求】
- 用词克制，不堆砌形容词；
- 每个结论后面都要能追溯到数据，没有数据支撑的判断不要写；
- 数字统一保留合理精度（金额到元、比率到小数点后两位）。
"""


